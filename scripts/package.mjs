/**
 * Assemble a browser-loadable (unpacked) extension folder.
 *
 * `tsc` compiles the sources to `dist/src/**`, preserving the directory layout
 * and ES module relative imports (e.g. `../core/constants.js`,
 * `../ui/messaging.js`). The browser, however, needs a folder whose
 * `manifest.json` and each HTML page sit next to the files they reference.
 * This script produces that folder at `./extension`:
 *
 *   extension/
 *     manifest.json   (service_worker -> background/index.js,
 *                      default_popup  -> popup/popup.html,
 *                      options_ui     -> options/options.html)
 *     background/  core/  ui/        (compiled .js; siblings so imports resolve)
 *     popup/    popup.html  popup.css    theme.css  popup.js
 *     options/  options.html options.css theme.css  options.js
 *
 * popup.html / options.html reference `theme.css`, their page css and js as
 * flat siblings, so each page folder gets its own copy of the shared theme.css.
 * The compiled JS keeps importing `../core`, `../ui`, `../background`, which
 * resolve because those folders are siblings of popup/ and options/.
 *
 * Run after `npm run build` (the `npm run package` script does both).
 */
import { cp, mkdir, rm, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const distSrc = join(root, 'dist', 'src');
const srcDir = join(root, 'src');
const out = join(root, 'extension');

if (!existsSync(distSrc)) {
  console.error('Missing dist/src. Run "npm run build" first.');
  process.exit(1);
}

// Start from a clean output folder.
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

// 1. Copy compiled JS modules (keeps background/ core/ ui/ popup/ options/ as
//    siblings so the relative ES imports between them resolve in the browser).
//    Strip tsc's dev-only outputs (.d.ts declarations and .js.map sourcemaps)
//    so the published package ships only the runtime .js.
const isDevArtifact = (p) =>
  p.endsWith('.d.ts') || p.endsWith('.js.map') || p.endsWith('.d.ts.map');
for (const dir of ['background', 'core', 'ui', 'popup', 'options']) {
  await cp(join(distSrc, dir), join(out, dir), {
    recursive: true,
    filter: (src) => !isDevArtifact(src),
  });
}

// 1b. Copy the rasterized toolbar/store icons (generated by scripts/icons.mjs)
//     into extension/icons so the manifest's icons / action.default_icon resolve.
const iconsSrc = join(root, 'branding', 'icons');
if (existsSync(iconsSrc)) {
  await cp(iconsSrc, join(out, 'icons'), { recursive: true });
} else {
  console.warn('Missing branding/icons. Run "npm run icons" to generate PNG icons.');
}

// 2. Copy static assets tsc does not emit: each page's html/css plus the shared
//    theme.css, placed as flat siblings next to the page's compiled js.
const sharedTheme = join(srcDir, 'ui', 'theme.css');
await cp(join(srcDir, 'popup', 'popup.html'), join(out, 'popup', 'popup.html'));
await cp(join(srcDir, 'popup', 'popup.css'), join(out, 'popup', 'popup.css'));
await cp(sharedTheme, join(out, 'popup', 'theme.css'));
await cp(join(srcDir, 'options', 'options.html'), join(out, 'options', 'options.html'));
await cp(join(srcDir, 'options', 'options.css'), join(out, 'options', 'options.css'));
await cp(sharedTheme, join(out, 'options', 'theme.css'));

// 3. Emit a manifest whose paths match the assembled layout.
const manifest = JSON.parse(await readFile(join(root, 'manifest.json'), 'utf8'));
manifest.background.service_worker = 'background/index.js';
manifest.action.default_popup = 'popup/popup.html';
if (manifest.options_ui) {
  manifest.options_ui.page = 'options/options.html';
}
await writeFile(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

console.log('Loadable extension written to ./extension');
